export function useTranslation() {
  const { language } = usePreferences();
  return useMemo(() => {
    const t = (key: string): string => {
      const entry = dictionary[key];
      if (!entry) return key;
      return language === 'ar' ? entry.ar : entry.en;
    };
    return { t, language };
  }, [language]);
}
